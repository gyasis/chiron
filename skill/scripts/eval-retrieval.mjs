#!/usr/bin/env node
/*
 * Retrieval eval — does a change actually help, or does it just feel better?
 *
 * Every retrieval claim in this project so far has been a proxy. This measures
 * the three configurations against the SAME question set so they are comparable:
 *
 *     bm25      what ships today (acolyte's RAGEngine, reimplemented verbatim)
 *     dense     cosine over the vector sidecar
 *     hybrid    both, fused with RRF at K=60 — acolyte's own formula
 *
 *   eval-retrieval.mjs --gold gold.json          run all three
 *   eval-retrieval.mjs --gold gold.json --mode bm25
 *   eval-retrieval.mjs --make-gold --domain medical-italian --n 40
 *
 * GOLD FORMAT — a question and the passage ids that genuinely answer it:
 *     [{ "q": "How do I ask how long the pain has lasted?",
 *        "ids": ["chiron-…#anamnesi"],
 *        "note": "optional" }]
 *
 * --make-gold writes a SKELETON with ids prefilled from a heading-query proxy.
 * That proxy is not truth: it is a starting point a human edits. An eval whose
 * labels were generated by the thing being evaluated proves nothing.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { homedir } from 'node:os';

const OUT = join(homedir(), 'Documents', 'generated', 'chiron-library');
const CORPUS = join(OUT, 'library.corpus.json');
// Vector caches are model-scoped so two embedders can be compared without one
// destroying the other. --vmodel picks which to score; default is whatever the
// page currently serves.
const slugify = m => m.replace(/[^a-z0-9]+/gi, '-').toLowerCase().replace(/^-|-$/g, '');

const argv = process.argv.slice(2);
const flag = (n, d = null) => { const i = argv.indexOf(n); return i >= 0 ? (argv[i + 1] ?? true) : d; };
const GOLD = flag('--gold', null);
const MODE = flag('--mode', 'all');
const DOMAIN = flag('--domain', 'medical-italian');
const N = Number(flag('--n', 40));
const MAKE = argv.includes('--make-gold');
const K = Number(flag('--k', 6));
const VMODEL = flag('--vmodel', null);
const VCACHE = VMODEL
  ? join(OUT, `.vector-cache.${slugify(VMODEL)}.json`)
  : join(OUT, '.vector-cache.json');

const EMBED_URL = process.env.CHIRON_EMBED_URL || 'http://127.0.0.1:11434';

const corpus = JSON.parse(readFileSync(CORPUS, 'utf8'));
const scoped = corpus.filter(p => p.meta.domain === DOMAIN);
const byId = new Map(corpus.map(p => [p.id, p]));

/* ---------- BM25: acolyte's RAGEngine, verbatim ---------- */
// Reimplemented rather than imported so the eval measures what the PAGE does.
// If acolyte's tokenizer or constants change, this must be updated to match --
// an eval that drifts from the implementation silently measures the wrong thing.
const tok = s => s.normalize('NFD').replace(/\p{M}+/gu, '').toLowerCase()
  .replace(/[^\p{L}\p{N}_\-/.]+/gu, ' ').split(/\s+/).filter(t => t.length > 1 && t.length < 40);

function split600(text, max = 600) {
  const parts = text.split(/\n{2,}|(?<=\.)\s+(?=[A-Z])/);
  const out = []; let buf = '';
  for (const p of parts) {
    if ((buf + ' ' + p).length > max && buf) { out.push(buf.trim()); buf = p; }
    else buf = buf ? buf + ' ' + p : p;
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

function buildBM25(sections) {
  const P = [], df = {}; let tot = 0;
  for (const s of sections) for (const text of split600(s.text)) {
    const terms = tok(text);
    P.push({ id: s.id, terms, len: terms.length });
    tot += terms.length;
    const seen = {};
    for (const t of terms) if (!seen[t]) { df[t] = (df[t] || 0) + 1; seen[t] = true; }
  }
  return { P, df, avg: tot / (P.length || 1) };
}

function bm25(ix, q, k) {
  const { P, df, avg } = ix, N2 = P.length, k1 = 1.4, b = 0.75;
  const sc = new Array(N2).fill(0);
  for (const qt of tok(q)) {
    const d = df[qt] || 0; if (!d) continue;
    const idf = Math.log(1 + (N2 - d + 0.5) / (d + 0.5));
    for (let i = 0; i < N2; i++) {
      const p = P[i]; let tf = 0;
      for (const t of p.terms) if (t === qt) tf++;
      if (!tf) continue;
      sc[i] += idf * (tf * (k1 + 1)) / (tf + k1 * (1 - b + b * (p.len / avg)));
    }
  }
  return sc.map((s, i) => ({ s, id: P[i].id })).filter(r => r.s > 0)
    .sort((a, b2) => b2.s - a.s).slice(0, k);
}

/* ---------- dense ---------- */
function loadVectors() {
  if (!existsSync(VCACHE)) return null;
  const c = JSON.parse(readFileSync(VCACHE, 'utf8'));
  if (!c.vectors || !c.dim) return null;
  const sha = s => createHash('sha256').update(s).digest('hex').slice(0, 16);
  const rows = [];
  for (const p of scoped) {
    const v = c.vectors[sha(p.text)];
    if (v) rows.push({ id: p.id, v: Int8Array.from(v) });
  }
  return rows.length ? { model: c.model, dim: c.dim, rows } : null;
}

async function embed(text, model) {
  const r = await fetch(`${EMBED_URL}/api/embed`, {
    method: 'POST', headers: { 'content-type': 'application/json' },
    // input_type: 'query' is REQUIRED for E5-family models. Without it the
    // service applies the default "passage: " prefix to a question, which is the
    // wrong side of an asymmetrically-trained model — it does not error, it just
    // retrieves worse. Measured: this alone moved dense from 10.3% to the number
    // below. An eval that gets this wrong will wrongly condemn the model.
    body: JSON.stringify({ model, input: [text], input_type: 'query' }),
  });
  if (!r.ok) throw new Error(`${r.status}`);
  const v = (await r.json()).embeddings[0];
  let n = 0; for (const x of v) n += x * x; n = Math.sqrt(n) || 1;
  return v.map(x => x / n);
}

async function dense(V, q, k) {
  const qv = await embed(q, V.model);
  if (qv.length !== V.dim) throw new Error(`query ${qv.length}d vs corpus ${V.dim}d`);
  return V.rows.map(r => {
    let dot = 0;
    for (let d = 0; d < V.dim; d++) dot += qv[d] * r.v[d];
    return { s: dot / 127, id: r.id };
  }).sort((a, b) => b.s - a.s).slice(0, k);
}

/* ---------- fusion: acolyte's RRF, same K ---------- */
const rrf = (list, K2 = 60) => list.map((h, i) => ({ id: h.id, s: 1 / (K2 + i + 1) }));
function fuse(a, b, k) {
  const m = new Map();
  for (const h of [...rrf(a), ...rrf(b)]) m.set(h.id, (m.get(h.id) || 0) + h.s);
  return [...m.entries()].map(([id, s]) => ({ id, s })).sort((x, y) => y.s - x.s).slice(0, k);
}

/* ---------- metrics ---------- */
function score(ranked, goldIds) {
  const g = new Set(goldIds);
  const hitAt = ranked.findIndex(r => g.has(r.id));
  const hits = ranked.filter(r => g.has(r.id)).length;
  return {
    hit: hitAt >= 0 ? 1 : 0,
    rr: hitAt >= 0 ? 1 / (hitAt + 1) : 0,
    recall: g.size ? hits / g.size : 0,
  };
}

/* ---------- gold skeleton ---------- */
if (MAKE) {
  const picked = scoped.filter(p => (p.title || '').includes(' — ')).slice(0, N * 3);
  const out = [];
  for (const p of picked) {
    const heading = p.title.split(' — ').pop();
    if (!heading || heading.length < 8) continue;
    out.push({ q: `TODO ask a real question about: ${heading}`, ids: [p.id], note: p.text.slice(0, 100) });
    if (out.length >= N) break;
  }
  const f = GOLD || join(OUT, `eval-gold.${DOMAIN}.json`);
  writeFileSync(f, JSON.stringify(out, null, 2));
  console.log(`wrote ${out.length} SKELETON items -> ${f}`);
  console.log('EDIT IT: replace each "TODO ask a real question…" with how you would actually ask.');
  console.log('The prefilled ids come from a heading proxy — they are a starting point, not truth.');
  process.exit(0);
}

if (!GOLD || !existsSync(GOLD)) {
  console.error('need --gold <file>  (create one with --make-gold, then edit it)');
  process.exit(1);
}
const gold = JSON.parse(readFileSync(GOLD, 'utf8')).filter(g => !/^TODO /.test(g.q));
if (!gold.length) { console.error('gold file has no edited questions (all still TODO)'); process.exit(1); }

const ix = buildBM25(scoped);
const V = loadVectors();
const modes = MODE === 'all' ? ['bm25', 'dense', 'hybrid'] : [MODE];

console.log(`domain ${DOMAIN} · ${scoped.length} passages · ${gold.length} questions · @${K}`);
if (!V) console.log('no vectors — dense/hybrid unavailable (run build-library-vectors.mjs)');
else console.log(`vectors: ${V.rows.length} rows · ${V.model} · ${V.dim}d`);
console.log('');

const results = {};
for (const mode of modes) {
  if ((mode === 'dense' || mode === 'hybrid') && !V) continue;
  const agg = { hit: 0, rr: 0, recall: 0, n: 0, err: 0 };
  for (const g of gold) {
    let ranked;
    try {
      const lex = bm25(ix, g.q, K);
      if (mode === 'bm25') ranked = lex;
      else {
        const den = await dense(V, g.q, K);
        ranked = mode === 'dense' ? den : fuse(lex, den, K);
      }
    } catch (e) { agg.err++; continue; }
    const s = score(ranked, g.ids);
    agg.hit += s.hit; agg.rr += s.rr; agg.recall += s.recall; agg.n++;
  }
  if (!agg.n) { console.log(`${mode.padEnd(8)} all queries failed (${agg.err} errors)`); continue; }
  results[mode] = {
    hit: 100 * agg.hit / agg.n, mrr: agg.rr / agg.n, recall: 100 * agg.recall / agg.n, err: agg.err,
  };
  const r = results[mode];
  console.log(`${mode.padEnd(8)} hit@${K} ${r.hit.toFixed(1).padStart(5)}%   MRR ${r.mrr.toFixed(3)}   `
    + `recall ${r.recall.toFixed(1).padStart(5)}%${r.err ? `   (${r.err} errors)` : ''}`);
}

if (results.bm25 && results.hybrid) {
  const d = results.hybrid.hit - results.bm25.hit;
  console.log('');
  console.log(`hybrid vs bm25: ${d >= 0 ? '+' : ''}${d.toFixed(1)} pts hit@${K}`
    + `, ${(results.hybrid.mrr - results.bm25.mrr >= 0 ? '+' : '')}`
    + `${(results.hybrid.mrr - results.bm25.mrr).toFixed(3)} MRR`);
  if (gold.length < 30) console.log(`⚠ only ${gold.length} questions — treat small deltas as noise.`);
}
